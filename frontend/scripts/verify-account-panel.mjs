import { chromium, expect } from '@playwright/test';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  let user = { id: 1, email: 'investor@example.com', role: 'user', display_name: 'Minh Anh', preferred_language: 'vi', timezone: 'Asia/Ho_Chi_Minh', email_verified_at: null };
  let failSave = false;
  let revoked = false;
  let singleRevoked = false;
  let failSessions = true;
  let sessionLabel = null;
  let failLabel = true;
  let failMore = true;
  await page.route('**/api/**', route => {
    const path = new URL(route.request().url()).pathname;
    if (path === '/api/auth/me') return route.fulfill({ json: { success: true, user } });
    if (path === '/api/auth/sessions') {
      if (failSessions) { failSessions = false; return route.fulfill({ status: 500, json: { success: false, message: 'Không thể tải phiên đăng nhập.' } }); }
      if (new URL(route.request().url()).searchParams.has('cursor')) {
        if (failMore) { failMore = false; return route.fulfill({ status: 500, json: { success: false, message: 'Tải thêm thất bại' } }); }
        return route.fulfill({ json: { success: true, data: { sessions: [{ id: 'current', current: true, label: sessionLabel }, { id: 'older', current: false, label: 'Phiên cũ hơn' }], can_revoke_others: true, has_more: false, next_cursor: null } } });
      }
      return route.fulfill({ json: { success: true, data: { sessions: [{ id: 'current', current: true, label: sessionLabel }, ...(!revoked ? [{ id: 'other', current: false }, ...(!singleRevoked ? [{ id: 'target', current: false }] : [])] : [])], can_revoke_others: true, has_more: !revoked, next_cursor: !revoked ? 'next-page' : null } } });
    }
    if (path === '/api/auth/sessions/label') {
      if (failLabel) { failLabel = false; return route.fulfill({ status: 500, json: { success: false, message: 'Không thể lưu tên phiên.' } }); }
      const body = route.request().postDataJSON();
      sessionLabel = body.label;
      return route.fulfill({ json: { success: true, data: { id: body.session_id, label: sessionLabel } } });
    }
    if (path === '/api/auth/sessions/revoke') {
      if (route.request().postDataJSON().session_id !== 'target') throw new Error('Wrong session targeted');
      singleRevoked = true;
      return route.fulfill({ json: { success: true } });
    }
    if (path === '/api/auth/sessions/revoke-others') { revoked = true; return route.fulfill({ json: { success: true, data: { revoked_count: 1 } } }); }
    if (path === '/api/auth/profile') {
      if (failSave) return route.fulfill({ status: 500, json: { success: false, message: 'Không thể lưu hồ sơ' } });
      user = { ...user, ...route.request().postDataJSON() };
      return route.fulfill({ json: { success: true, user } });
    }
    return route.fulfill({ json: { success: true, data: path === '/api/stocks' || path === '/api/watchlist' ? [] : { positions: [], transactions: [] } } });
  });
  await page.goto('http://127.0.0.1:4173');
  const trigger = page.getByRole('button', { name: 'Tài khoản và thông tin cá nhân', exact: true });
  await trigger.click();
  const dialog = page.getByRole('dialog');
  await expect(dialog).toBeVisible();
  await expect(dialog.getByText('Chưa xác thực', { exact: true })).toBeVisible();
  await expect(dialog.getByLabel('Email đăng nhập')).toHaveAttribute('readonly', '');
  const save = dialog.getByRole('button', { name: 'Lưu thay đổi' });
  await expect(save).toBeDisabled();
  await dialog.getByLabel('Họ và tên', { exact: true }).fill('Nguyễn An');
  await dialog.getByLabel('Ngày sinh', { exact: true }).fill('2000-02-29');
  await dialog.getByLabel('Số điện thoại', { exact: true }).fill('+84912345678');
  await dialog.getByLabel('Ngôn ngữ và định dạng', { exact: true }).selectOption('en');
  await dialog.getByLabel('Múi giờ', { exact: true }).selectOption('Asia/Singapore');
  await save.click();
  await expect(save).toBeDisabled();
  if (user.full_name !== 'Nguyễn An' || user.date_of_birth !== '2000-02-29' || user.phone !== '+84912345678' || user.preferred_language !== 'en' || user.timezone !== 'Asia/Singapore') throw new Error('Profile details payload mismatch');
  await expect(page.locator('html')).toHaveAttribute('lang', 'vi');
  await expect(page.locator('html')).toHaveAttribute('data-locale', 'en');
  await expect(page.locator('html')).toHaveAttribute('data-timezone', 'Asia/Singapore');
  await dialog.getByLabel('Họ và tên', { exact: true }).fill('Draft');
  await dialog.getByRole('button', { name: 'Hoàn tác', exact: true }).click();
  await expect(dialog.getByLabel('Họ và tên', { exact: true })).toHaveValue('Nguyễn An');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/profile-expanded-mobile.png' });
  await page.setViewportSize({ width: 1280, height: 900 });
  const profileTab = dialog.getByRole('tab', { name: 'Hồ sơ', exact: true });
  const securityTab = dialog.getByRole('tab', { name: 'Bảo mật', exact: true });
  await profileTab.focus();
  await page.keyboard.press('ArrowRight');
  await expect(securityTab).toBeFocused();
  await expect(securityTab).toHaveAttribute('aria-selected', 'true');
  await expect(dialog.locator('.account-sessions').getByRole('alert')).toContainText('Không thể tải phiên đăng nhập.');
  await dialog.getByRole('button', { name: 'Làm mới phiên' }).click();
  await expect(dialog.getByText('Phiên hiện tại', { exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Xem thêm phiên', exact: true }).click();
  await expect(dialog.locator('.account-sessions').getByRole('alert')).toContainText('Tải thêm thất bại');
  await expect(dialog.locator('.account-session-list li')).toHaveCount(3);
  await dialog.getByRole('button', { name: 'Xem thêm phiên', exact: true }).click();
  await expect(dialog.getByText('Phiên cũ hơn', { exact: true })).toBeVisible();
  await expect(dialog.locator('.account-session-list li')).toHaveCount(4);
  await expect(dialog.getByText('Phiên hiện tại', { exact: true })).toHaveCount(1);
  await expect(dialog.getByRole('button', { name: 'Xem thêm phiên', exact: true })).toHaveCount(0);
  await dialog.getByRole('button', { name: 'Đặt tên phiên', exact: true }).first().click();
  await expect(dialog.getByLabel('Tên phiên do bạn đặt')).toBeFocused();
  await dialog.getByLabel('Tên phiên do bạn đặt').fill('Laptop cá nhân');
  await page.keyboard.press('Escape');
  await expect(dialog.getByText('Bạn có thay đổi chưa lưu')).toBeVisible();
  await dialog.getByRole('button', { name: 'Tiếp tục chỉnh sửa', exact: true }).click();
  await expect(dialog.getByLabel('Tên phiên do bạn đặt')).toBeFocused();
  await expect(dialog.getByRole('button', { name: 'Đổi mật khẩu và đăng nhập lại' })).toBeDisabled();
  await dialog.getByRole('button', { name: 'Lưu tên phiên', exact: true }).click();
  await expect(dialog.locator('.account-sessions').getByRole('alert')).toContainText('Không thể lưu tên phiên.');
  await expect(dialog.getByLabel('Tên phiên do bạn đặt')).toHaveValue('Laptop cá nhân');
  await dialog.getByRole('button', { name: 'Lưu tên phiên', exact: true }).click();
  await expect(dialog.getByText('Laptop cá nhân', { exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Làm mới phiên' }).click();
  await expect(dialog.getByText('Laptop cá nhân', { exact: true })).toBeVisible();
  await dialog.locator('.account-session-list li').first().getByRole('button', { name: 'Đổi tên phiên', exact: true }).click();
  await dialog.getByLabel('Tên phiên do bạn đặt').fill('');
  await dialog.getByRole('button', { name: 'Lưu tên phiên', exact: true }).click();
  await expect(dialog.getByText('Phiên hiện tại', { exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Đăng xuất phiên khác 2', exact: true }).click();
  await dialog.getByRole('button', { name: 'Giữ phiên này', exact: true }).click();
  if (singleRevoked) throw new Error('Cancellation revoked session');
  await dialog.getByRole('button', { name: 'Đăng xuất phiên khác 2', exact: true }).click();
  await dialog.getByRole('button', { name: 'Xác nhận đăng xuất phiên này', exact: true }).click();
  await expect(dialog.getByText('Đã đăng xuất phiên đã chọn. Các phiên khác vẫn được giữ.')).toBeVisible();
  await expect(dialog.getByRole('button', { name: 'Đăng xuất phiên khác 2', exact: true })).toHaveCount(0);
  await expect(dialog.getByRole('button', { name: 'Đăng xuất phiên khác 1', exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Đăng xuất các phiên khác', exact: true }).click();
  await dialog.getByRole('button', { name: 'Hủy đăng xuất phiên', exact: true }).click();
  if (revoked) throw new Error('Cancel revoked sessions');
  await dialog.getByRole('button', { name: 'Đăng xuất các phiên khác', exact: true }).click();
  await dialog.getByRole('button', { name: 'Xác nhận đăng xuất phiên khác' }).click();
  await expect(dialog.getByText('Đã đăng xuất các phiên khác. Phiên hiện tại vẫn được giữ.')).toBeVisible();
  await expect(dialog.getByRole('button', { name: 'Đăng xuất các phiên khác', exact: true })).toBeDisabled();
  await expect(dialog.getByLabel('Tên hiển thị')).not.toBeVisible();
  await dialog.getByLabel('Mật khẩu hiện tại', { exact: true }).fill('draft-only-test');
  await securityTab.press('Home');
  await expect(profileTab).toHaveAttribute('aria-selected', 'true');
  await profileTab.press('End');
  await expect(dialog.getByLabel('Mật khẩu hiện tại', { exact: true })).toHaveValue('draft-only-test');
  await page.keyboard.press('Escape');
  await dialog.getByRole('button', { name: 'Tiếp tục chỉnh sửa' }).click();
  await expect(dialog.getByLabel('Mật khẩu hiện tại', { exact: true })).toBeFocused();
  await page.keyboard.press('Escape');
  await dialog.getByRole('button', { name: 'Bỏ thay đổi và đóng' }).click();
  await trigger.click();
  await securityTab.click();
  await expect(dialog.getByLabel('Mật khẩu hiện tại', { exact: true })).toHaveValue('');
  await profileTab.click();
  await dialog.getByLabel('Tên hiển thị').fill('Chưa lưu');
  await securityTab.click();
  await expect(dialog.getByRole('button', { name: 'Đổi mật khẩu và đăng nhập lại' })).toBeDisabled();
  await dialog.getByRole('button', { name: 'Quay lại Hồ sơ' }).click();
  await expect(dialog.getByLabel('Tên hiển thị')).toHaveValue('Chưa lưu');
  await page.keyboard.press('Escape');
  await expect(dialog.getByText('Bạn có thay đổi chưa lưu')).toBeVisible();
  await expect(dialog.getByRole('button', { name: 'Tiếp tục chỉnh sửa' })).toBeFocused();
  await dialog.getByRole('button', { name: 'Tiếp tục chỉnh sửa' }).click();
  await expect(dialog.getByLabel('Tên hiển thị')).toHaveValue('Chưa lưu');
  await dialog.getByRole('button', { name: 'Đăng xuất', exact: true }).click();
  await expect(dialog.getByRole('button', { name: 'Bỏ thay đổi và đăng xuất' })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(dialog.getByText('Bạn có thay đổi chưa lưu')).not.toBeVisible();
  await expect(dialog.getByLabel('Tên hiển thị')).toBeFocused();
  await dialog.getByRole('button', { name: 'Đóng thông tin cá nhân' }).click();
  await dialog.getByRole('button', { name: 'Bỏ thay đổi và đóng' }).click();
  await expect(dialog).not.toBeVisible();
  await trigger.click();
  await expect(dialog.getByLabel('Tên hiển thị')).toHaveValue('Minh Anh');
  await dialog.getByLabel('Tên hiển thị').fill('An Nguyễn');
  await save.click();
  await expect(dialog.getByText('Đã lưu thông tin cá nhân.')).toBeVisible();
  await expect(trigger).toContainText('An Nguyễn');
  failSave = true;
  await dialog.getByLabel('Tên hiển thị').fill('Bản nháp');
  await save.click();
  await expect(dialog.getByRole('alert')).toBeVisible();
  await expect(dialog.getByLabel('Tên hiển thị')).toHaveValue('Bản nháp');
  await dialog.getByRole('button', { name: 'Hoàn tác' }).click();
  await page.screenshot({ path: 'test-results/account-desktop.png' });
  await page.keyboard.press('Escape');
  await expect(dialog).not.toBeVisible();
  await expect(trigger).toBeFocused();
  await page.locator('.sidebar-toggle').click();
  await trigger.click();
  await expect(dialog).toBeVisible();
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 });
  await trigger.click();
  await expect(dialog).toBeVisible();
  if (await dialog.evaluate(el => el.scrollWidth > el.clientWidth + 1)) throw new Error('Dialog overflow');
  await page.screenshot({ path: 'test-results/account-mobile.png' });
  await securityTab.click();
  if (await dialog.evaluate(el => el.scrollWidth > el.clientWidth + 1)) throw new Error('Security panel overflow');
  await page.screenshot({ path: 'test-results/account-security-mobile.png' });
  await dialog.getByRole('button', { name: 'Đóng thông tin cá nhân' }).click();
  await expect(dialog).not.toBeVisible();
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('Account panel: save, error/retry draft, readonly email, Escape/focus, collapsed sidebar and mobile passed (mock API).');
} finally { await browser.close(); }
